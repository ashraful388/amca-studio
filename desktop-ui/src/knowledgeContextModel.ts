// ZCODE-AMCA-STUDIO-V0.8.0-KNOWLEDGE-WORKFLOW-UX-INTEGRATION-01 — pure model.
//
// Explicit, USER-CONTROLLED knowledge context attachment for the chat
// composer, over the recorded knowledge surface (the artifact registry via
// knowledgeUxModel). Rules recorded by the order:
// - the user picks items explicitly; NOTHING is attached automatically and
//   nothing is retrieved in the background;
// - add/remove happens before execution — the selection is composer state;
// - each selection shows its provenance references and retrieval metadata;
// - empty / unavailable / permission-denied are first-class honest states;
// - the context rides in the EXISTING goal contract as a transparent
//   annotation — the same recorded mechanism the composer already uses for
//   the task-type tag ([Task type: …], LIMITATION_RECORDS #5) — because the
//   chat-run contract has no separate knowledge field and backend changes
//   are out of scope.

import type { KnowledgeAssetView } from "./knowledgeUxModel";

export const MAX_KNOWLEDGE_CONTEXT_ITEMS = 5;

/** One user-selected knowledge context item (recorded fields only). */
export interface KnowledgeContextItem {
  artifactId: string;
  title: string;
  typeLabel: string;
  currentVersion: number;
  /** Shareability verdict from the recorded knowledge model — verbatim. */
  shareability: "shareable" | "restricted" | "private";
  shareabilityReason: string;
  /** Provenance summary rendered from the recorded provenance chain. */
  provenanceLine: string;
}

/**
 * Build a context item from a recorded knowledge asset view. Provenance is
 * taken verbatim from the asset record (project, creator, artifact id +
 * version); nothing is inferred.
 */
export function toContextItem(asset: KnowledgeAssetView): KnowledgeContextItem {
  const creatorPart = asset.creator && asset.creator !== "unknown" ? ` · generated by ${asset.creator}` : "";
  return {
    artifactId: asset.artifactId,
    title: asset.title,
    typeLabel: asset.typeLabel,
    currentVersion: asset.currentVersion,
    shareability: asset.shareability,
    shareabilityReason: asset.shareabilityReason,
    provenanceLine: `Project ${asset.projectId.slice(0, 12)}${creatorPart} · ${asset.typeLabel} v${asset.currentVersion} · ${asset.artifactId}`,
  };
}

export interface KnowledgeSelectionValidation {
  ok: boolean;
  errors: string[];
}

/** Selection guard: bounded count, no duplicates. */
export function validateSelection(items: KnowledgeContextItem[]): KnowledgeSelectionValidation {
  const errors: string[] = [];
  if (items.length > MAX_KNOWLEDGE_CONTEXT_ITEMS) {
    errors.push(`At most ${MAX_KNOWLEDGE_CONTEXT_ITEMS} knowledge items can be attached.`);
  }
  const ids = new Set(items.map((item) => item.artifactId));
  if (ids.size !== items.length) errors.push("Duplicate knowledge items are not allowed.");
  return { ok: errors.length === 0, errors };
}

export type KnowledgeContextAddResult =
  | { ok: true; items: KnowledgeContextItem[] }
  | { ok: false; reason: "duplicate" | "limit"; message: string };

/** Add one item to the selection — explicit only, guarded, no side effects. */
export function addToSelection(
  current: KnowledgeContextItem[],
  asset: KnowledgeAssetView,
): KnowledgeContextAddResult {
  if (current.some((item) => item.artifactId === asset.artifactId)) {
    return { ok: false, reason: "duplicate", message: "Already attached — each item can be attached once." };
  }
  if (current.length >= MAX_KNOWLEDGE_CONTEXT_ITEMS) {
    return { ok: false, reason: "limit", message: `At most ${MAX_KNOWLEDGE_CONTEXT_ITEMS} knowledge items can be attached.` };
  }
  return { ok: true, items: [...current, toContextItem(asset)] };
}

/** Retrieval metadata shown with the selection: recorded facts only. */
export function selectionMetadata(items: KnowledgeContextItem[]): string {
  if (items.length === 0) return "";
  return `${items.length} item(s) · selected manually · no automatic retrieval · context rides in the run goal text`;
}

/**
 * Render the transparent context annotation appended to the run goal —
 * the recorded goal-tag mechanism (same pattern as "[Task type: …]").
 * Empty selection renders nothing.
 */
export function knowledgeContextTag(items: KnowledgeContextItem[]): string {
  if (items.length === 0) return "";
  const lines = items.map(
    (item) => `- ${item.title} (${item.typeLabel} v${item.currentVersion}, ${item.artifactId})`,
  );
  return `\n\n[Knowledge context — attached explicitly by the user (${items.length} item(s), no automatic retrieval)]\n${lines.join("\n")}`;
}

/** Wrap a message with the context annotation (empty selection = message unchanged). */
export function withKnowledgeContext(message: string, items: KnowledgeContextItem[]): string {
  return `${message.trimEnd()}${knowledgeContextTag(items)}`;
}

// ---------- Honest states ----------

export const KNOWLEDGE_CONTEXT_EMPTY = {
  title: "No knowledge assets yet",
  detail: "Artifacts authored by runs appear here as attachable knowledge once a task completes.",
} as const;

export const KNOWLEDGE_CONTEXT_UNAVAILABLE = {
  title: "Knowledge list unavailable",
  detail: "The artifact registry could not be read, so no knowledge items are shown — nothing is assumed or auto-attached.",
} as const;

/** Permission-denied presentation for a non-shareable asset (verbatim reason). */
export function permissionLine(item: KnowledgeContextItem): string {
  if (item.shareability === "shareable") return "Shareable — can be attached";
  return `${item.shareability === "private" ? "Private" : "Restricted"} — ${item.shareabilityReason}`;
}
