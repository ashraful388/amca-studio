// ZCODE-AMCA-STUDIO-V0.8.0-COGNITIVE-WORKFLOW-UX-FOUNDATION-01 tests.
// Minimum coverage per the order: full workflow rendering, partial
// rendering, missing records, no reasoning leakage, knowledge provenance,
// governance transparency, empty states.

import { test } from "node:test";
import assert from "node:assert/strict";
import {
  WORKFLOW_STAGE_LABELS,
  workflowStages,
  workflowPosition,
  workflowPanelView,
  resourceTransparency,
  knowledgeUsage,
  verificationView,
  WORKFLOW_PANEL_EMPTY,
} from "../src/cognitiveWorkflowUxModel.ts";

const run = (overrides = {}) => ({
  run_id: "run-abc-123",
  status: "succeeded",
  created_at: "2026-09-03T10:00:00Z",
  finished_at: "2026-09-03T10:05:00Z",
  ...overrides,
});

const knowledge = (id) => ({
  artifactId: id,
  title: `Report ${id}`,
  typeLabel: "Reports & notes",
  currentVersion: 2,
  shareability: "shareable",
  shareabilityReason: "Locally produced output — shareable in principle.",
  provenanceLine: `Project proj-1234567890 · generated by agent-7 · Reports & notes v2 · ${id}`,
});

// ---------- the mandated 9 stages ----------

test("timeline renders the mandated 9 stages in order, recorded states only", () => {
  assert.deepEqual(WORKFLOW_STAGE_LABELS, [
    "Task created",
    "Understanding complete",
    "Plan created",
    "Resources selected",
    "Knowledge attached",
    "Execution started",
    "Execution completed",
    "Verification complete",
    "Learning recorded",
  ]);
  const stages = workflowStages(run(), [knowledge("a1")]);
  assert.equal(stages.length, 9);
  assert.deepEqual(stages.map((s) => s.label), WORKFLOW_STAGE_LABELS);
  // recorded: created, understanding, resources, knowledge, execution done
  const states = Object.fromEntries(stages.map((s) => [s.id, s.state]));
  assert.equal(states.task_created, "done");
  assert.equal(states.understanding_complete, "done");
  assert.equal(states.resources_selected, "done");
  assert.equal(states.knowledge_attached, "done");
  assert.equal(states.execution_started, "done");
  assert.equal(states.execution_completed, "done");
  // orchestrator-side stages have no desktop record — Not recorded, never inferred
  assert.equal(states.plan_created, "not_recorded");
  assert.equal(states.verification_complete, "not_recorded");
  assert.equal(states.learning_recorded, "not_recorded");
});

test("partial rendering: queued run shows active execution and not-recorded completion", () => {
  const stages = workflowStages(run({ status: "queued", finished_at: null }), []);
  const byId = Object.fromEntries(stages.map((s) => [s.id, s]));
  assert.equal(byId.task_created.state, "done");
  assert.equal(byId.execution_started.state, "not_recorded");
  assert.equal(byId.execution_completed.state, "not_recorded");
});

test("failed run records the failure state and the recorded error only", () => {
  const stages = workflowStages(run({ status: "failed", error: "converter crashed" }), []);
  const byId = Object.fromEntries(stages.map((s) => [s.id, s]));
  assert.equal(byId.execution_completed.state, "failed");
  assert.equal(byId.execution_completed.detail, "converter crashed");
  assert.equal(byId.verification_complete.state, "not_recorded");
});

// ---------- missing records / empty states ----------

test("missing run record: every stage is Not recorded with no invented timestamps", () => {
  const stages = workflowStages(null, []);
  assert.equal(stages.length, 9);
  for (const stage of stages) {
    assert.equal(stage.state, "not_recorded");
    assert.equal(stage.timestamp, null);
    assert.equal(workflowPosition(stages), "Not recorded");
  }
});

test("knowledge-attached stage reflects the user's explicit selection", () => {
  const withNone = workflowStages(run(), []);
  assert.equal(withNone.find((s) => s.id === "knowledge_attached")?.state, "not_recorded");
  const withOne = workflowStages(run(), [knowledge("a9")]);
  const stage = withOne.find((s) => s.id === "knowledge_attached");
  assert.equal(stage?.state, "done");
  assert.ok(stage?.detail?.includes("attached explicitly by the user"));
  assert.equal(workflowPosition(withOne), "Execution completed");
});

// ---------- panel fields ----------

test("panel fields derive from records; task type parsed from the recorded tag or Not recorded", () => {
  const tagged = workflowPanelView({ ...run(), goal: "[Task type: Research] Compare catalysts" });
  assert.equal(tagged.workflowId, "run-abc-123");
  assert.equal(tagged.taskType, "Research");
  assert.equal(tagged.lifecycleState, "succeeded");
  const untagged = workflowPanelView({ ...run(), goal: "No tag here" });
  assert.equal(untagged.taskType, null);
  const blank = workflowPanelView({ ...run(), goal: "  " });
  assert.equal(blank.userGoal, "Not recorded");
  const failed = workflowPanelView({ ...run({ status: "failed", error: "boom" }), goal: "x" });
  assert.equal(failed.failureReason, "boom");
});

// ---------- governance transparency, no reasoning leakage ----------

test("resource transparency states locality and governance without routing reasoning", () => {
  const local = resourceTransparency(["ollama:qwen", "ollama:llama"], ["agent-1"]);
  assert.ok(local.locality.includes("Local models only"));
  const mixed = resourceTransparency(["ollama:qwen", "prov:gpt"], []);
  assert.ok(mixed.locality.includes("Mixed: 1 local, 1 provider"));
  const api = resourceTransparency(["cred-9"], []);
  assert.ok(api.locality.includes("approval required"));
  const none = resourceTransparency([], []);
  assert.equal(none.locality, "Not recorded");
  for (const view of [local, mixed, api, none]) {
    assert.ok(view.governanceStatus.includes("exact approval before any network call"));
    // no hidden reasoning: no scores, no percentages
    assert.ok(!/\d+%/.test(view.governanceStatus));
  }
});

// ---------- knowledge provenance + audit reference ----------

test("knowledge usage lines carry provenance, permission, retrieval mode, audit ref", () => {
  const lines = knowledgeUsage([knowledge("a1"), knowledge("a2")], "aud-123");
  assert.equal(lines.length, 2);
  for (const line of lines) {
    assert.ok(line.provenance.includes("generated by agent-7"));
    assert.equal(line.permissionStatus, "Shareable — can be attached");
    assert.ok(line.retrievalMode.includes("no automatic retrieval"));
    assert.equal(line.auditReference, "aud-123");
  }
  const withoutAudit = knowledgeUsage([knowledge("a1")], null);
  assert.equal(withoutAudit[0].auditReference, null);
});

// ---------- verification without scores ----------

test("verification reports outcome, artifacts, evidence; never scores", () => {
  const done = verificationView(run({ status: "succeeded" }), ["Catalyst report"]);
  assert.ok(done.outcome.includes("completed"));
  assert.deepEqual(done.artifacts, ["Catalyst report"]);
  assert.ok(done.validationEvidence.includes("succeeded"));
  const failed = verificationView(run({ status: "failed", error: "x" }), []);
  assert.deepEqual(failed.unresolvedIssues, ["x"]);
  assert.equal(failed.validationEvidence, "Not recorded");
  const none = verificationView(null, []);
  assert.equal(none.outcome, "Not recorded");
  assert.deepEqual(none.artifacts, []);
  const rendered = JSON.stringify(done);
  assert.ok(!/confidence|quality score|rating/i.test(rendered));
});

// ---------- empty-state documentation constant ----------

test("empty state explains the orchestrator boundary honestly", () => {
  assert.ok(WORKFLOW_PANEL_EMPTY.title.includes("No cognitive workflow record"));
  assert.ok(WORKFLOW_PANEL_EMPTY.detail.includes("Not recorded"));
});
