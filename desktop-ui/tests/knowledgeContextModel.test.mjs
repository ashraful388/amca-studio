// ZCODE-AMCA-STUDIO-V0.8.0-KNOWLEDGE-WORKFLOW-UX-INTEGRATION-01 tests.
// Covers the explicit user-controlled knowledge context flow: selection
// guards, provenance/metadata display, the transparent goal-tag mechanism,
// and the honest empty/unavailable/permission states.

import { test } from "node:test";
import assert from "node:assert/strict";
import {
  MAX_KNOWLEDGE_CONTEXT_ITEMS,
  toContextItem,
  addToSelection,
  validateSelection,
  selectionMetadata,
  knowledgeContextTag,
  withKnowledgeContext,
  KNOWLEDGE_CONTEXT_EMPTY,
  KNOWLEDGE_CONTEXT_UNAVAILABLE,
  permissionLine,
} from "../src/knowledgeContextModel.ts";
import { knowledgeAssets } from "../src/knowledgeUxModel.ts";

// fixture through the real recorded knowledge model (provenance verbatim)
const asset = (overrides = {}) => knowledgeAssets([{
  artifactId: "art-1",
  projectId: "proj-abcdef123456",
  title: "Catalyst report",
  type: "markdown",
  version: 3,
  creator: "agent-7",
  ...overrides,
}])[0];

const shareable = asset();
// The recorded shareability model: agent/model-created -> shareable,
// anything authored outside the governed pipeline -> private.
const private_ = asset({ artifactId: "art-2", title: "Client memo", type: "docx", version: 1, creator: "unknown" });
const private2 = asset({ artifactId: "art-3", title: "Scratch", type: "text", version: 1, creator: "unknown" });

// ---------- explicit selection building ----------

test("context items carry recorded provenance verbatim, nothing inferred", () => {
  const item = toContextItem(shareable);
  assert.equal(item.artifactId, "art-1");
  assert.equal(item.title, "Catalyst report");
  assert.equal(item.typeLabel, "Reports & notes");
  assert.equal(item.currentVersion, 3);
  assert.ok(item.provenanceLine.includes("proj-abcdef123456".slice(0, 12)));
  assert.ok(item.provenanceLine.includes("generated by agent-7"));
  assert.ok(item.provenanceLine.includes("art-1"));
  const unknownCreator = toContextItem(private_);
  assert.ok(!unknownCreator.provenanceLine.includes("generated by"));
});

test("add is explicit, duplicate-safe, and bounded", () => {
  const first = addToSelection([], shareable);
  assert.equal(first.ok, true);
  const again = addToSelection(first.ok ? first.items : [], shareable);
  assert.equal(again.ok, false);
  assert.equal(again.ok ? "" : again.reason, "duplicate");

  const full = [];
  for (let i = 0; i < MAX_KNOWLEDGE_CONTEXT_ITEMS; i += 1) {
    const step = addToSelection(full, asset({ artifactId: `art-${i}` }));
    assert.equal(step.ok, true);
    if (step.ok) full.push(...step.items.slice(-1));
  }
  const over = addToSelection(full, asset({ artifactId: "art-x" }));
  assert.equal(over.ok, false);
  assert.equal(over.ok ? "" : over.reason, "limit");
  assert.ok(over.ok ? "" : over.message.includes(String(MAX_KNOWLEDGE_CONTEXT_ITEMS)));
});

test("validation rejects duplicates and over-limit selections", () => {
  const one = toContextItem(shareable);
  assert.equal(validateSelection([one, one]).ok, false);
  assert.equal(validateSelection([one]).ok, true);
  const many = Array.from({ length: MAX_KNOWLEDGE_CONTEXT_ITEMS + 1 }, (_, i) => toContextItem(asset({ artifactId: `a${i}` })));
  assert.equal(validateSelection(many).ok, false);
});

// ---------- retrieval metadata transparency ----------

test("selection metadata states the recorded retrieval facts", () => {
  const meta = selectionMetadata([toContextItem(shareable)]);
  assert.ok(meta.includes("selected manually"));
  assert.ok(meta.includes("no automatic retrieval"));
  assert.ok(meta.includes("run goal text"));
  assert.equal(selectionMetadata([]), "");
});

// ---------- transparent goal-tag mechanism ----------

test("context rides in the goal as a recorded transparent annotation", () => {
  const items = [toContextItem(shareable)];
  const tag = knowledgeContextTag(items);
  assert.ok(tag.includes("[Knowledge context — attached explicitly by the user (1 item(s), no automatic retrieval)]"));
  assert.ok(tag.includes("- Catalyst report (Reports & notes v3, art-1)"));
  const two = withKnowledgeContext("Analyze this.", [...items, toContextItem(private_)]);
  assert.ok(two.startsWith("Analyze this."));
  assert.ok(two.includes("(2 item(s)"));
  // empty selection leaves the message untouched (no empty tag block)
  assert.equal(withKnowledgeContext("Analyze this.", []), "Analyze this.");
  assert.equal(knowledgeContextTag([]), "");
});

// ---------- honest states ----------

test("empty, unavailable, and permission states are recorded verbatim", () => {
  assert.equal(KNOWLEDGE_CONTEXT_EMPTY.title, "No knowledge assets yet");
  assert.ok(KNOWLEDGE_CONTEXT_UNAVAILABLE.detail.includes("nothing is assumed or auto-attached"));

  assert.equal(permissionLine(toContextItem(shareable)), "Shareable — can be attached");
  const privateLine = permissionLine(toContextItem(private_));
  assert.ok(privateLine.startsWith("Private —"));
  assert.ok(privateLine.includes(toContextItem(private_).shareabilityReason));
});

test("non-agent-authored assets resolve as private through the recorded model", () => {
  // the permission-denied path comes from the recorded shareability model
  assert.equal(toContextItem(private_).shareability, "private");
  assert.equal(toContextItem(private2).shareability, "private");
  assert.ok(toContextItem(private_).shareabilityReason.includes("never shares automatically"));
  assert.equal(toContextItem(shareable).shareability, "shareable");
});
