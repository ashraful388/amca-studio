test("unknown keys fall back to the generic empty state", () => {
  assert.equal(knowledgeEmptyState("mystery").title, "Nothing here yet");
  assert.equal(knowledgeEmptyState("no_assets").title, "No knowledge assets yet");
});

test("backend disclosure states exactly what this build does and does not record", () => {
  assert.match(KNOWLEDGE_BACKEND_NOTE, /artifact registry/);
  assert.match(KNOWLEDGE_BACKEND_NOTE, /Knowledge backend is not present/);
  assert.match(KNOWLEDGE_BACKEND_NOTE, /display as such/);
});
