import { test } from "node:test";
import assert from "node:assert/strict";
import {
  fromArtifactItem,
  knowledgeTypeLabel,
  creatorKind,
  shareability,
  knowledgeAssets,
  knowledgeCollections,
  provenanceChain,
  knowledgeRelations,
  knowledgeEmptyState,
  KNOWLEDGE_EMPTY_STATES,
  KNOWLEDGE_BACKEND_NOTE,
} from "../src/knowledgeUxModel.ts";

const ASSET = (overrides) => ({
  artifactId: "art-1",
  projectId: "p1",
  title: "Lemma proof",
  type: "markdown",
  typeLabel: "Reports & notes",
  currentVersion: 2,
  creator: "model:ollama=qwen3:1.7b",
  createdByKind: "model",
  shareability: "shareable",
  shareabilityReason: "",
  ...overrides,
});

const META = (overrides) => ({
  artifact_id: "art-1", project_id: "p1", artifact_type: "markdown", title: "Lemma proof",
  created_by: "model:ollama=qwen3:1.7b", current_version: 2, ...overrides,
});

// ---------- Type labels / creator kinds ----------

test("type labels map the recorded artifact types", () => {
  assert.equal(knowledgeTypeLabel("markdown"), "Reports & notes");
  assert.equal(knowledgeTypeLabel("pdf"), "PDF outputs");
  assert.equal(knowledgeTypeLabel("weird"), "weird");
});

test("creator kind is classified from the recorded creator string", () => {
  assert.equal(creatorKind("agent:scheduler"), "agent");
  assert.equal(creatorKind("model:ollama=qwen3"), "model");
  assert.equal(creatorKind("user:manual"), "user");
  assert.equal(creatorKind("weird-origin"), "unknown");
});

// ---------- Shareability ----------

test("agent/model output is shareable-potential with the no-external-sharing caveat", () => {
  const safety = shareability({ creatorKind: "model", type: "markdown" });
  assert.equal(safety.state, "shareable");
  assert.match(safety.reason, /no external sharing/);
  assert.match(safety.reason, /nothing leaves the device/);
});

test("non-governed documents are private by default", () => {
  const safety = shareability({ creatorKind: "user", type: "docx" });
  assert.equal(safety.state, "private");
  assert.match(safety.reason, /private/);
});

// ---------- Browser ----------

test("browser maps artifact records into asset views", () => {
  const assets = knowledgeAssets([
    { artifactId: "a", projectId: "p1", title: "Lemma proof", type: "markdown", version: 2, creator: "model:ollama=qwen3:1.7b" },
    { artifactId: "b", projectId: "p1", title: "Report", type: "pdf", version: 1, creator: "agent:scheduler" },
  ]);
  assert.equal(assets.length, 2);
  assert.equal(assets[0].typeLabel, "Reports & notes");
  assert.equal(assets[1].createdByKind, "agent");
  assert.equal(assets[1].shareability, "shareable");
});

test("fromArtifactItem extracts creator from recorded provenance fields", () => {
  const input = fromArtifactItem({
    artifact_id: "x", project_id: "p", artifact_type: "docx", title: "T",
    current_version_number: 1, provenance: { created_by: "model:gpt" },
  });
  assert.equal(input.creator, "model:gpt");
  const view = knowledgeAssets([input])[0];
  assert.equal(view.createdByKind, "model");
  assert.equal(view.currentVersion, 1);
});

test("items without provenance degrade to unknown creator and private safety", () => {
  const view = knowledgeAssets([fromArtifactItem({
    artifact_id: "y", project_id: "p", artifact_type: "docx", title: "T2",
    current_version_number: 1, provenance: {},
  })])[0];
  assert.equal(view.creator, "unknown");
  assert.equal(view.createdByKind, "unknown");
  assert.equal(view.shareability, "private");
});

test("collections group by type with counts, sorted by count then label", () => {
  const assets = knowledgeAssets([
    { artifactId: "a", projectId: "p", title: "A", type: "markdown", version: 1, creator: "model:m" },
    { artifactId: "b", projectId: "p", title: "B", type: "markdown", version: 1, creator: "model:m" },
    { artifactId: "c", projectId: "p", title: "C", type: "pdf", version: 1, creator: "model:m" },
  ]);
  const collections = knowledgeCollections(assets);
  assert.deepEqual(collections, [
    { type: "markdown", label: "Reports & notes", count: 2 },
    { type: "pdf", label: "PDF outputs", count: 1 },
  ]);
});

test("empty registry yields no collections", () => {
  assert.deepEqual(knowledgeCollections(knowledgeAssets([])), []);
});

// ---------- Provenance ----------

test("provenance chain records creator, workflow, storage; memory unknown", () => {
  const steps = provenanceChain(ASSET({ projectId: "p1234567890", creator: "model:ollama=qwen3:1.7b", currentVersion: 3 }));
  const byStage = new Map(steps.map((step) => [step.stage, step]));
  assert.equal(byStage.get("Created from")?.recorded, true);
  assert.match(byStage.get("Created from")?.value ?? "", /Project p1234567890/);
  assert.equal(byStage.get("Generated by")?.value, "model:ollama=qwen3:1.7b");
  assert.match(byStage.get("Stored as")?.value, /v3 · art-1/);
  assert.equal(byStage.get("Memory reference")?.recorded, false);
});

test("unknown creator leaves the generated-by step unrecorded", () => {
  const steps = provenanceChain(ASSET({ creator: "unknown" }));
  assert.equal(steps.find((step) => step.stage === "Generated by")?.recorded, false);
});

// ---------- Relations ----------

test("relations connect same collection, creator, and project without inference", () => {
  const asset = ASSET({ artifactId: "a", type: "markdown", creator: "model:ollama", projectId: "p1" });
  const all = [
    asset,
    ASSET({ artifactId: "b", type: "markdown", creator: "model:ollama", projectId: "p2" }),
    ASSET({ artifactId: "c", type: "pdf", creator: "model:ollama", projectId: "p1" }),
    ASSET({ artifactId: "d", type: "pdf", creator: "user:manual", projectId: "p2" }),
  ];
  const relations = knowledgeRelations(asset, all);
  const idsByKind = new Map(relations.map((relation) => [relation.kind, relation.relatedId]));
  // Maps keep the LAST entry per kind when several relations share one;
  // assert membership instead of ordering.
  const byKind = new Map();
  for (const relation of relations) {
    if (!byKind.has(relation.kind)) byKind.set(relation.kind, new Set());
    byKind.get(relation.kind).add(relation.relatedId);
  }
  assert.ok(byKind.get("same_collection").has("b"));
  assert.ok(byKind.get("same_creator").has("b"));
  assert.ok(byKind.get("same_project").has("c"));
});

test("an asset alone has no relations", () => {
  const asset = ASSET({ artifactId: "a" });
  assert.deepEqual(knowledgeRelations(asset, [asset]), []);
});

