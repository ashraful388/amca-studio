# ---------------------------------------------------------------------------

def _ga_declaration_check(text: str) -> bool:
    """Mirror of the guard's scan logic for direct regression testing."""
    import re as _re

    strip_pattern = _re.compile(
        r"\b[A-Z0-9]+(?:-[A-Z0-9]+)*-V?1\.0\.0(?:-[A-Z0-9]+)+\b")
    scan_pattern = _re.compile(
        r"\bv?1\.0\.0\b[^.]{0,60}?(?:\bGA\b|\bis released\b|"
        r"\breleased to the public\b|\bgeneral availability\b)",
        _re.IGNORECASE)
    for line in text.splitlines():
        cleaned = strip_pattern.sub("", line)
        if scan_pattern.search(cleaned):
            return True
    return False


def test_standalone_ga_tokens_detected_case_insensitive():
    for line in ("AMCA Studio v1.0.0 GA",
                 "AMCA Studio v1.0.0 is GA",
                 "AMCA Studio v1.0.0 ga",
                 "AMCA Studio v1.0.0 Ga"):
        assert _ga_declaration_check(line), f"must detect: {line}"


def test_punctuation_adjacent_ga_detected():
    for line in ("AMCA Studio v1.0.0 (GA)",
                 "AMCA Studio v1.0.0 - GA!",
                 "AMCA Studio v1.0.0, GA."):
        assert _ga_declaration_check(line), f"must detect: {line}"


