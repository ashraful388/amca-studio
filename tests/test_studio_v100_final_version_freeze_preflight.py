def test_simulated_bump_stale_detection_is_version_aware():
    """Pre-transition (0.9.0): the simulated 1.0.0 bump flags every active
    declaration. Post-transition (1.0.0): only derived release records may
    remain stale (regenerated by the pipeline)."""
    result = simulate_version_bump()
    assert result["read_only"] is True
    assert result["target_version"] == "1.0.0"
    files_flagged = {s["file"].split(":")[0] for s in result["stale_active_references"]}
    if TRANSITION_DONE:
        for s in result["stale_active_references"]:
            assert s["file"].startswith("dist/"), f"non-derived stale: {s['file']}"
    else:
        for loc in ACTIVE_VERSION_DECLARATIONS:
            if loc.kind != "derived":
                assert loc.file in files_flagged, f"{loc.file} not flagged"


def test_simulated_bump_code_reference_detection_version_aware():
    """Every code reference that embeds the simulated old version literal is
    flagged, at its actual line, and nothing outside the inventoried files is
    ever reported."""
    from amca.version_freeze_preflight import CURRENT_VERSION

    result = simulate_version_bump()
    flagged = {s["file"] for s in result["stale_active_references"]}
    code_flagged = {f for f in flagged if ":" in f}

    # Independent scan of the inventoried modules for the old-version literal.
    expected: set[str] = set()
    for loc in ACTIVE_CODE_REFERENCES:
        path = SOFTWARE_ROOT / loc.file
        if not path.is_file():
            continue
        for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if f'"{CURRENT_VERSION}"' in line or f"'{CURRENT_VERSION}'" in line:
                expected.add(f"{loc.file}:{lineno}")
    assert code_flagged == expected
    for entry in result["stale_active_references"]:
        if entry["file"] in code_flagged:
            assert entry["current"] == CURRENT_VERSION
            assert entry["required"] == result["target_version"]


def test_simulated_bump_flags_derived_release_records_for_regeneration():
    from amca.version_freeze_preflight import CURRENT_VERSION

    result = simulate_version_bump()
    regenerate = [s for s in result["stale_active_references"]
                  if "regenerate" in s["why"]]
    names = {s["file"] for s in regenerate}
    # Every derived release record that physically exists under the simulated
    # old version must be flagged for regeneration.
    expected = {
        loc.file.format(version=CURRENT_VERSION)
        for loc in DERIVED_RELEASE_RECORDS
        if loc.file.format(version=CURRENT_VERSION)
        != loc.file.format(version=result["target_version"])
        and (SOFTWARE_ROOT / loc.file.format(version=CURRENT_VERSION)).exists()
    }
    assert expected, "at least one stale derived record must be present to flag"
    assert expected <= names
    for entry in regenerate:
        assert entry["file"].startswith("dist/")
        assert "never hand-edit" in entry["why"]
    # The checksums file has no version in its name but must also be
    # regenerated; it is inventoried under DERIVED_RELEASE_RECORDS.
    sums = [loc for loc in DERIVED_RELEASE_RECORDS if loc.file.endswith("SHA256SUMS.txt")]
    assert len(sums) == 1


