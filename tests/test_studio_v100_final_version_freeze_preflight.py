def test_final_bump_checklist_is_complete_and_ordered():
    checklist = final_bump_checklist()
    text = "\n".join(checklist).lower()
    # Dependency ordering: tauri conf before cargo lock regeneration; pipeline
    # regeneration after code-reference updates; certification before tag;
    # tag before promotion.
    tauri_idx = next(i for i, s in enumerate(checklist) if "tauri.conf.json" in s.lower())
    cargo_idx = next(i for i, s in enumerate(checklist) if "cargo.lock" in s.lower())
    pipeline_idx = next(i for i, s in enumerate(checklist) if "run_distribution_pipeline" in s)
    cert_idx = next(i for i, s in enumerate(checklist)
                    if "certification evidence pass" in s.lower())
    tag_idx = next(i for i, s in enumerate(checklist) if "amca-studio-v1.0.0" in s
                   and "tag" in s.lower())
    promo_idx = next(i for i, s in enumerate(checklist)
                     if "promote_final_release" in s and "--dry-run" in s)
    assert tauri_idx < cargo_idx < pipeline_idx < cert_idx < tag_idx < promo_idx
    assert "clean tree" in text
    assert "candidate" in text  # release-note transition present
