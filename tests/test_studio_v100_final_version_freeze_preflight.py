def test_no_premature_v1_ga_declaration():
    """No active doc may declare v1.0.0 GA/released before final certification."""
    import re

    docs_dir = SOFTWARE_ROOT / "docs" / "release"
    for doc in docs_dir.glob("AMCA-Studio-v1.0.0-*.md"):
        text = doc.read_text(encoding="utf-8")
        # I2F.1A GA-token hardening: MILESTONE-ID tokens (uppercase-hyphen
        # joined, e.g. "OPENCODE-PS2-AMCA-STUDIO-V1.0.0-I2U-PS2-AGGREGATE-
        # 01") are stripped BEFORE scanning so their embedded version token
        # and ID fragments never contribute release language. A genuine
        # standalone version token ("v1.0.0" / "1.0.0") in prose is KEPT, and
        # a standalone GA token (\bGA\b, case-insensitive) or release verb
        # near it IS detected; substrings (AGGREGATE/GATE/GAMMA/ENGAGEMENT/
        # MEGABYTE) are not, thanks to word boundaries.
        declares_ga = None
        for line in text.splitlines():
            cleaned = re.sub(
                r"\b[A-Z0-9]+(?:-[A-Z0-9]+)*-V?1\.0\.0(?:-[A-Z0-9]+)+\b",
                "", line)
            m = re.search(
                r"\bv?1\.0\.0\b[^.]{0,60}?(?:\bGA\b|\bis released\b|"
                r"\breleased to the public\b|\bgeneral availability\b)",
                cleaned, re.IGNORECASE)
            if m:
                declares_ga = m
                break
        if declares_ga:
            lowered = text.lower()
            assert ("candidate" in lowered or "pending" in lowered or
                    "not yet" in lowered or "do not declare" in lowered), (
                f"{doc.name} appears to declare GA prematurely"
            )


