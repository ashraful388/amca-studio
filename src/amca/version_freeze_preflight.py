def _read_text(relative: str) -> Optional[str]:
    path = SOFTWARE_ROOT / relative
    if not path.is_file():
        return None
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return None


def _extract_toml_version(text: str) -> Optional[str]:
    for line in text.splitlines():
        if line.strip().startswith("version"):
            return line.split("=", 1)[1].strip().strip('"').strip("'")
    return None


def _extract_json_version(text: str) -> Optional[str]:
    try:
        return json.loads(text).get("version")
    except (json.JSONDecodeError, OSError):
        return None


def _extract_python_version(text: str) -> Optional[str]:
    m = re.search(r'^__version__\s*=\s*["\']([^"\']+)["\']', text, re.MULTILINE)
    return m.group(1) if m else None


def read_active_version_matrix() -> Dict[str, Any]:
    """Read every active declaration's current version value."""
    extractors = {"toml": _extract_toml_version,
                  "json": _extract_json_version,
                  "python": _extract_python_version}
    matrix: Dict[str, Any] = {}
    for loc in ACTIVE_VERSION_DECLARATIONS:
        if loc.kind == "derived":
            matrix[loc.file] = {
                "role": loc.role, "kind": loc.kind, "version": None,
                "note": loc.note, "derived": True,
            }
            continue
        text = _read_text(loc.file)
        version = extractors[loc.kind](text) if text else None
        matrix[loc.file] = {
            "role": loc.role, "kind": loc.kind, "version": version,
            "note": loc.note, "derived": False,
        }
    return matrix


def active_version_agreement(matrix: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Do all non-derived active declarations currently agree?"""
    matrix = matrix or read_active_version_matrix()
    concrete = {f: v["version"] for f, v in matrix.items() if not v["derived"]}
    distinct = {v for v in concrete.values() if v}
    return {
        "versions": concrete,
        "distinct_versions": sorted(distinct),
        "agrees": len(distinct) == 1,
        "current_version": next(iter(distinct)) if len(distinct) == 1 else None,
    }


def simulate_version_bump(target: str = TARGET_VERSION) -> Dict[str, Any]:
    """Dry-run: what would still disagree if the active version became
    `target`? Classifies every 0.9.0 reference in active code/records as
    either historical (allowed) or stale active metadata (must change).

    Read-only: this performs NO file modification.
    """
    matrix = read_active_version_matrix()
    agreement = active_version_agreement(matrix)

    stale_active: List[Dict[str, str]] = []
    # 1. Active declarations that would not match the target.
    for loc in ACTIVE_VERSION_DECLARATIONS:
        if loc.kind == "derived":
            continue
        entry = matrix.get(loc.file, {})
        if entry.get("version") not in (None, target):
            stale_active.append({
                "file": loc.file, "role": loc.role,
                "current": str(entry.get("version")),
                "required": target,
                "why": "active version declaration must move with the bump",
            })

    # 2. Active code references that embed the CURRENT version literal.
    for loc in ACTIVE_CODE_REFERENCES:
        text = _read_text(loc.file)
        if text is None:
            continue
        for lineno, line in enumerate(text.splitlines(), start=1):
            if f'"{CURRENT_VERSION}"' in line or f"'{CURRENT_VERSION}'" in line:
                stale_active.append({
                    "file": f"{loc.file}:{lineno}",
                    "role": loc.role,
                    "current": CURRENT_VERSION,
                    "required": target,
                    "why": f"active code reference ({loc.note})",
                })

    # 3. Derived release records whose filenames embed the current version.
    for loc in DERIVED_RELEASE_RECORDS:
        expected_old = loc.file.format(version=CURRENT_VERSION)
        expected_new = loc.file.format(version=target)
        if (SOFTWARE_ROOT / expected_old).exists() and expected_old != expected_new:
            stale_active.append({
                "file": expected_old,
                "role": loc.role,
                "current": CURRENT_VERSION,
                "required": target,
                "why": f"derived release record must be regenerated as {expected_new} "
                       "(regenerate via tooling; never hand-edit)",
            })

    return {
        "schema": "amca-version-freeze-preflight/1",
        "target_version": target,
        "active_version_agreement": agreement,
        "stale_active_references": stale_active,
        "stale_count": len(stale_active),
        "historical_exemptions": HISTORICAL_EXEMPTIONS,
        "candidate_documents": CANDIDATE_DOCUMENTS,
        "tag_contract": {
            "convention": RELEASE_TAG_CONVENTION,
            "next_release_tag": RELEASE_TAG,
            "rules": [
                "tag target must equal the final certified source SHA",
                "tag must not point to a report-only follow-up commit unless "
                "that is deliberately the final canonical source",
                "promotion evidence must record the tag",
                "tag creation occurs only after final certification PASS",
                "do not create the tag now",
            ],
        },
        "read_only": True,
    }


