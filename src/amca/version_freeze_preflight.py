RELEASE_TAG = RELEASE_TAG_CONVENTION.format(version=TARGET_VERSION)

# ---------------------------------------------------------------------------
# Active version declaration inventory (each entry: file, extraction, role)
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class VersionLocation:
    file: str  # relative to software root
    role: str
    kind: str  # "toml" | "json" | "python" | "derived"
    note: str = ""


#: The authoritative list of ACTIVE version declarations that must move from
