"""AMCA Studio v1.0.0 Final Version Freeze / Tagging Preflight (I2F).

Milestone: ZCODE-AMCA-STUDIO-V1.0.0-I2F-FINAL-VERSION-FREEZE-TAGGING-AND-RELEASE-METADATA-TRANSITION-PREFLIGHT-01

Read-only validator that answers: "What would still disagree if the active
version became 1.0.0?" — distinguishing historical references (allowed to
remain 0.9.0) from stale active metadata (must change at bump time).

Zero production/version changes: this module never writes anything. It is
the deterministic preflight so the eventual 0.9.0 -> 1.0.0 bump is a small,
controlled operation once PS-1 freezes the final canonical SHA.
"""

