def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _ps_quote(path: Path) -> str:
    return str(path).replace("'", "''")


def inspect_authenticode(path: Path) -> Dict[str, Any]:
    """Inspect one file's Authenticode signature via Windows tooling.

    Returns a dict; never infers from the filename. For non-PE files (e.g.
    zip archives) Authenticode does not apply and status is recorded as such.
    """
    if sys_platform_windows() is False:
        return {"status": "UNAVAILABLE", "reason": "not a Windows host"}
    script = (
        "$s = Get-AuthenticodeSignature -FilePath '" + _ps_quote(path) + "'; "
        "$ts = $null -ne $s.TimeStamperCertificate; "
        "$out = [ordered]@{"
        "status = [string]$s.Status; "
        "statusMessage = [string]$s.StatusMessage; "
        "signer = if ($s.SignerCertificate) { [string]$s.SignerCertificate.Subject } else { '' }; "
        "timestamped = [bool]$ts; "
        "hashAlgorithm = if ($s.SignerCertificate) { [string]$s.SignerCertificate.SignatureAlgorithm.FriendlyName } else { '' }; "
        "chainStatus = [string]($s.Status -join ',')"
        "}; "
        "$out | ConvertTo-Json -Compress"
    )
    try:
        proc = subprocess.run(
            ["powershell", "-NoProfile", "-Command", script],
            capture_output=True, text=True, timeout=120,
        )
        if proc.returncode != 0:
            return {"status": "INSPECTION_ERROR",
                    "reason": proc.stderr.strip()[:200] or "powershell failed"}
        data = json.loads(proc.stdout.strip() or "{}")
        return {
            "status": data.get("status", "UNKNOWN"),
            "status_message": data.get("statusMessage", ""),
            "signer": data.get("signer") or None,
            "timestamped": bool(data.get("timestamped")),
            "hash_algorithm": data.get("hashAlgorithm") or None,
        }
    except (subprocess.TimeoutExpired, json.JSONDecodeError, OSError) as exc:
        return {"status": "INSPECTION_ERROR", "reason": str(exc)[:200]}


def sys_platform_windows() -> bool:
    import os

    return os.name == "nt"


def inventory_signing_targets(dist_dir: Optional[Path] = None,
                              version: str = "0.9.0") -> List[Dict[str, Any]]:
    """Enumerate every executable in the actual distribution chain, with its
    signing classification from the signing-order contract."""
    dist = Path(dist_dir) if dist_dir else SOFTWARE_ROOT / "dist"
    targets: List[Dict[str, Any]] = []

    setup = dist / f"amca-studio-v{version}-windows-x64-setup.exe"
    targets.append({
        "artifact": setup.name,
        "path": str(setup) if setup.is_file() else None,
        "classification": "sign directly (after bundling)",
        "distributed_to_users": True,
    })
    portable = dist / f"amca-studio-v{version}-windows-x64-portable.zip"
    targets.append({
        "artifact": portable.name,
        "path": str(portable) if portable.is_file() else None,
        "classification": "inherits signed-member trust only (archive not "
                          "Authenticode-signable)",
        "distributed_to_users": True,
    })

    # Inspect portable members (the actual distributed exes).
    if portable.is_file():
        with tempfile.TemporaryDirectory(prefix="amca-signaudit-") as td:
            try:
                with zipfile.ZipFile(portable) as z:
                    z.extractall(td)
                for exe in sorted(Path(td).rglob("*.exe")):
                    classification = "sign directly"
                    if exe.name.lower() == "uninstall.exe":
                        classification = ("generated post-build; needs "
                                          "signing-order consideration")
                    targets.append({
                        "artifact": exe.name,
                        "path": str(exe),
                        "classification": classification,
                        "distributed_to_users": True,
                        "member_of": portable.name,
                    })
            except (zipfile.BadZipFile, OSError):
                pass

    backend = SOFTWARE_ROOT / "backend-dist" / "amca-backend.exe"
    if backend.is_file() and not any(
        t["artifact"] == "amca-backend.exe" for t in targets
    ):
        targets.append({
            "artifact": "amca-backend.exe", "path": str(backend),
            "classification": "sign directly", "distributed_to_users": True,
            "member_of": None,
        })
    desktop = (SOFTWARE_ROOT / "desktop-ui" / "src-tauri" / "target"
               / "release" / "amca-desktop.exe")
    if desktop.is_file() and not any(
        t["artifact"] == "amca-desktop.exe" for t in targets
    ):
        targets.append({
            "artifact": "amca-desktop.exe", "path": str(desktop),
            "classification": "sign directly", "distributed_to_users": True,
            "member_of": None,
        })
    return targets


def run_signing_audit(
    dist_dir: Optional[Path] = None,
    version: str = "0.9.0",
    signing_configured: bool = False,
) -> Dict[str, Any]:
    """Full machine-readable signing audit for the current artifacts.

    Overall verdict semantics:
    - PASS: every distributed PE is validly signed (with timestamp).
    - REVIEW: artifacts are unsigned while signing is intentionally not
      configured (current expected state) - honest for audit purposes.
    - BLOCKED: signing required for release but unavailable, signing command
      failed, or an invalid/expired/untrusted signature was found.
    """
    targets = inventory_signing_targets(dist_dir, version)

    # Ensure portable members are available for inspection: extract into a
    # disposable temp dir and add member paths to the inventory. The dir is
    # removed after the audit dict is built; recorded SHA256 evidence stays
    # bound to the exact bytes that were inspected.
    dist = Path(dist_dir) if dist_dir else SOFTWARE_ROOT / "dist"
    portable = dist / f"amca-studio-v{version}-windows-x64-portable.zip"
    member_paths: Dict[str, Path] = {}
    extraction_tmp: Optional[Path] = None
    if portable.is_file():
        extraction_tmp = Path(tempfile.mkdtemp(prefix="amca-signaudit-members-"))
        try:
            with zipfile.ZipFile(portable) as z:
                z.extractall(extraction_tmp)
            for exe in sorted(extraction_tmp.rglob("*.exe")):
                member_paths.setdefault(exe.name, exe)
        except (zipfile.BadZipFile, OSError):
            pass

    results: List[Dict[str, Any]] = []
    for t in targets:
        path: Optional[Path] = None
        if t.get("path") and Path(t["path"]).is_file():
            path = Path(t["path"])
        elif t["artifact"] in member_paths:
            path = member_paths[t["artifact"]]

        if path is None or not path.is_file():
            results.append({
                **t, "sha256": None, "inspection": {
                    "status": "ARTIFACT_MISSING"},
                "signing_relevant": t["artifact"].lower().endswith(".exe"),
            })
            continue
        is_pe = path.read_bytes()[:2] == b"MZ"
        inspection = inspect_authenticode(path) if is_pe else {
            "status": "NOT_APPLICABLE",
            "reason": "archive container; Authenticode applies to PE files; "
                      "members carry their own signatures",
        }
        results.append({
            **t, "sha256": sha256_file(path), "inspection": inspection,
            "signing_relevant": is_pe,
        })

    distributed_pes = [r for r in results if r.get("signing_relevant")]
    all_signed = bool(distributed_pes) and all(
        r["inspection"]["status"] == "Valid" for r in distributed_pes
    )
    any_error = any(
        r["inspection"]["status"] in ("INSPECTION_ERROR", "UnknownError")
        for r in distributed_pes
    )
    any_invalid = any(
        r["inspection"]["status"] in ("HashMismatch", "NotTrusted",
                                      "Expired", "Incompatible")
        for r in distributed_pes
    )
    unsigned = [r for r in distributed_pes
                if r["inspection"]["status"] == "NotSigned"]

    if extraction_tmp is not None:
        import shutil as _shutil
        _shutil.rmtree(extraction_tmp, ignore_errors=True)

    if all_signed:
        overall = VERDICT_PASS
    elif any_invalid or (any_error and signing_configured):
        overall = VERDICT_BLOCKED
    elif any_error:
        # Tool/inspection failure without a configured signing policy:
        # still not trustworthy for a signed release - honest REVIEW with
        # the failure recorded, never a silent PASS.
        overall = VERDICT_REVIEW
    elif unsigned and signing_configured:
        overall = VERDICT_BLOCKED
    else:
        overall = VERDICT_REVIEW

    return {
        "schema": "amca-windows-signing-audit/1",
        "timestamp_utc": _utc_now(),
        "version": version,
        "signing_policy": (
            "configured" if signing_configured
            else SIGNING_POLICY_NOT_CONFIGURED),
        "artifacts": results,
        "signing_order_contract": SIGNING_ORDER,
        "pipeline_integration_points": PIPELINE_INTEGRATION_POINTS,
        "signing_config_schema": SIGNING_CONFIG_SCHEMA,
        "smartscreen_boundary": {
            "statement": (
                "Code signing establishes publisher integrity/authenticity. "
                "SmartScreen reputation is NOT guaranteed merely by signing; "
                "reputation accrues over downloads/installs. No claim is made "
                "that signing guarantees warning-free Windows installation, "
                "and no EV/OV outcome is claimed unless a certificate is "
                "actually configured and tested."),
            "marketing_promises": "none",
        },
        "release_blocker_assessment": (
            "Signing is NOT currently a functional release blocker for the "
            "certified distribution itself; it IS a policy decision for "
            "public/commercial distribution (unsigned binaries trigger "
            "SmartScreen/Defender warnings and carry no publisher identity). "
            "Final signed-release readiness is BLOCKED_FOR_SIGNED_RELEASE "
            "until a certificate is configured."
        ),
        "overall": overall,
        "unsigned_artifacts": [r["artifact"] for r in unsigned],
        "secrets_exposed": False,
    }
